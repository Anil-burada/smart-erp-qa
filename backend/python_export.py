"""Export reviewed or draft JSON workflows as inspectable Playwright Python.

The export does NOT execute code, open browsers, sign in, or silently change
project locators.  Existing replay/approval gates remain the authority.
"""
from __future__ import annotations

import re
from backend.json_workflow import read_library, VARIABLE_PATTERN
from backend.locator import LocatorSpec, Workflow
from backend.registry import get_project

CRITICAL = re.compile(r'\b(save|submit|create|approve|post|delete|remove|confirm|release|receive|issue)\b', re.I)


def locator_python(spec) -> str:
    s = LocatorSpec.model_validate(spec)
    if s.kind == 'role' and s.role and s.name:
        return f'page.get_by_role({s.role!r}, name={s.name!r}, exact=True)'
    if s.kind == 'css' and s.value:
        return f'page.locator({s.value!r})'
    methods = {'test_id': 'get_by_test_id', 'label': 'get_by_label',
               'placeholder': 'get_by_placeholder', 'text': 'get_by_text',
               'title': 'get_by_title'}
    if s.kind in methods and s.value:
        exact = ', exact=True' if s.kind in ('label', 'placeholder', 'text', 'title') else ''
        return f'page.{methods[s.kind]}({s.value!r}{exact})'
    raise ValueError('Invalid locator definition for generated Python')


def value_python(value) -> str:
    if isinstance(value, str) and value.startswith('${'):
        match = VARIABLE_PATTERN.fullmatch(value)
        if not match:
            raise ValueError('Invalid runtime variable expression')
        return f'test_data[{match.group(1)!r}]'
    return repr(value)


def generate_python(workflow: Workflow) -> str:
    project = get_project(workflow.project_id)
    if not project:
        raise ValueError('ERP project not registered')
    library = read_library(workflow.project_id) if workflow.schema_version == 2 else None
    # Make sure the in-use locator library has not drifted from the approved/draft version.
    if library:
        from backend.json_workflow import fingerprint
        if workflow.locator_fingerprint != fingerprint(workflow, library):
            raise ValueError('Locator library changed. Review the workflow before generating code')
    lines = [
        '# Generated by Smart ERP QA from an existing project-specific JSON workflow.',
        '# REVIEW BEFORE RUNNING. Opening or logging in to an ERP is intentionally omitted.',
        '# This is a code export, not an automatic test or assertion of business correctness.',
        f'# Project: {workflow.project_id}  Workflow: {workflow.name}',
        f'# Approval at export: {"reviewed" if workflow.reviewed else "DRAFT / NOT APPROVED"}',
        'from urllib.parse import urlsplit',
        'from playwright.sync_api import Page, expect',
        '',
        'def replay(page: Page, test_data: dict | None = None, allow_writes: bool = False):',
        '    test_data = test_data or {}',
        '    outputs = {}',
        f'    project_environment = {project["environment"]!r}',
        "    if project_environment == 'production':",
        "        raise ValueError('Code export refuses to replay against production')",
        f'    project_root = {project["url"]!r}',
        '    current, root = urlsplit(page.url), urlsplit(project_root)',
        "    prefix = root.path.rstrip('/')",
        "    if (current.scheme, current.netloc) != (root.scheme, root.netloc) or not (current.path.rstrip('/') == prefix or current.path.startswith(prefix + '/')):",
        "        raise ValueError('Browser is not at the selected ERP project')",
        "    if page.locator('input[type=\"password\"]:visible').count():",
        "        raise ValueError('Log in manually before replaying the workflow')",
    ]
    if not workflow.reviewed:
        lines += ["    raise ValueError('Draft workflow: review and approve it in the dashboard, then export again')"]
    if any(s.action == 'click' and CRITICAL.search((s.target_text or '') + ' ' + (s.target or '')) for s in workflow.steps):
        lines += ["    if not allow_writes:", "        raise ValueError('Confirm test/staging write actions using allow_writes=True')"]
    if not workflow.steps:
        lines.append('    return outputs')
    for number, step in enumerate(workflow.steps, start=1):
        spec = library.fields[step.target].locator if library else step.locator
        if spec is None:
            raise ValueError(f'No locator for step {number}')
        expr = locator_python(spec)
        step_label = re.sub(r'[\r\n\u2028\u2029]', ' ', step.target_text or 'element')[:60]
        lines.append(f'    # Step {number}: {step.action}  ({step_label})')
        lines.append(f'    target = {expr}')
        action = step.action
        if action == 'click': lines.append('    target.click()')
        elif action == 'fill':
            lines.append(f'    fill_value = {value_python(step.value)}')
            lines.append("    target.fill('' if fill_value is None else str(fill_value))")
        elif action == 'select_option': lines.append(f'    target.select_option(str({value_python(step.value)}))')
        elif action in ('check','uncheck'): lines.append(f'    target.{action}()')
        elif action == 'press': lines.append(f'    target.press(str({value_python(step.value)}))')
        elif action == 'assert_visible': lines.append('    expect(target).to_be_visible()')
        elif action == 'assert_text': lines.append(f'    expect(target).to_have_text(str({value_python(step.value)}))')
        elif action == 'assert_value': lines.append(f'    expect(target).to_have_value(str({value_python(step.value)}))')
        elif action in ('capture_text','capture_value'):
            if not step.output or not re.fullmatch(r'[a-z][a-z0-9_]{0,79}', step.output):
                raise ValueError(f'Step {number} missing valid output name')
            method = 'inner_text' if action == 'capture_text' else 'input_value'
            lines.append(f'    outputs[{step.output!r}] = target.{method}().strip()')
        else:
            raise ValueError(f'Unsupported step action: {action}')
    lines += ['    return outputs', '']
    result = '\n'.join(lines)
    compile(result, f'{workflow.name}.py', 'exec')
    return result
